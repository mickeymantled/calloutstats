import { RelativeTime } from "./RelativeTime";
import type { Meta } from "@/lib/types";

/** Sticky "last updated" strip: run timestamp plus profiles succeeded / failed, from meta.json. */
export function UpdatedBar({ meta }: { meta: Meta }) {
  const run = meta.run;
  const status = run?.status ?? null;
  const badge = status === "ok" ? "ok" : status === "partial" ? "warn" : status === "failed" ? "bad" : "";
  return (
    <div className="updated-bar" role="status">
      <div className="container">
        {run ? (
          <>
            <span>Last updated <strong><RelativeTime iso={run.finishedAt ?? run.startedAt} /></strong></span>
            <span><strong className="pos">{run.profilesOk}</strong> profiles succeeded · <strong className={run.profilesFailed > 0 ? "neg" : ""}>{run.profilesFailed}</strong> failed{run.profilesTotal ? ` · ${run.profilesTotal} total` : ""}</span>
            {status && <span className={`badge ${badge}`} title={run.notes ?? undefined}>run {status}</span>}
          </>
        ) : (
          <span>No scrape run recorded yet{meta.generatedAt ? <> · bundle exported <strong><RelativeTime iso={meta.generatedAt} /></strong></> : null}.</span>
        )}
        <span className="faint">{meta.kolCount} KOLs · {meta.calloutCount} callouts</span>
        {meta.fixture && <span className="badge fixture" title="Generated by scripts/make-fixture-data.ts; not real pump.fun data">fixture data</span>}
      </div>
    </div>
  );
}
